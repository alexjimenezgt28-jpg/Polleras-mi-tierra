export function coloresDe(color: string): string[] {
  const partes = color
    .split(/\s+y\s+|\s*,\s*/i)
    .map((parte) => parte.trim())
    .filter((parte) => parte !== "")
    .map((parte) => parte.charAt(0).toUpperCase() + parte.slice(1).toLowerCase());
  return Array.from(new Set(partes));
}

